export function sizeOf(hero, index) {
  const sizes = hero?.sizes || []
  const at = Number.isInteger(index) ? index : hero?.defaultSize ?? 0
  return sizes[at] || sizes[hero?.defaultSize ?? 0] || sizes[0] || null
}
