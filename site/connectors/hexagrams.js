export const HEXAGRAMS = TEXT.map((row, index) => {
  const n = index + 1
  const [lower, upper] = PAIR[index]
  const lines = [...TRI[lower], ...TRI[upper]].map(Number)
  const [name, hint, tone, meaning, a] = row
  return {
    id: `hex-${n}`,
    n,
    mark: String.fromCodePoint(0x4dc0 + index),
    name,
    hint,
    tone,
    meaning,
    a,
    lines,
    img: `assets/hex/${n}.webp`,
  }
})

const BY_ID = Object.fromEntries(HEXAGRAMS.map((card) => [card.id, card]))

export function hexById(id) {
  return BY_ID[id] || null
}

export function hexByNumber(n) {
  return HEXAGRAMS[n - 1] || null
}

export function flipLine(lines, index) {
  return lines.map((bit, i) => (i === index ? 1 - bit : bit))
}

export function hexFromLines(lines) {
  const key = lines.join("")
  return HEXAGRAMS.find((card) => card.lines.join("") === key) || null
}

/** Три монеты: надпись = 2 (инь), гладкая сторона = 3 (ян). Сумма 6/7/8/9. */
export function tossLine(random) {
  const coins = [0, 1, 2].map(() => (random() < 0.5 ? 2 : 3))
  const sum = coins[0] + coins[1] + coins[2]
  return {
    coins,
    sum,
    yang: sum === 7 || sum === 9,
    moving: sum === 6 || sum === 9,
  }
}

export function castCoins(random) {
  return Array.from({ length: 6 }, () => tossLine(random))
}

export function layHexagram(input, random = Math.random) {
  const question = String(input?.question || "").trim()
  const asked = Array.isArray(input?.roles) && input.roles.length ? input.roles : ["Знак"]
  const throws = castCoins(random)
  const lines = throws.map((row) => (row.yang ? 1 : 0))
  const moving = throws.map((row, index) => (row.moving ? index : -1)).filter((index) => index >= 0)
  const first = hexFromLines(lines) || HEXAGRAMS[0]
  const wantChange = asked.length > 1
  const cards = [{
    role: asked[0] || "Знак",
    card: first,
    changing: moving,
    note: first.hint,
  }]
  if (wantChange) {
    if (moving.length) {
      const nextLines = lines.map((bit, index) => (moving.includes(index) ? 1 - bit : bit))
      const next = hexFromLines(nextLines) || first
      const how = moving.length === 1 ? "одна старшая черта" : `${moving.length} старших черт`
      cards.push({
        role: asked[1] || "Перемена",
        card: next,
        note: `Монеты дали ${how}. Знак переходит в «${next.name}» — ${next.hint}.`,
      })
    } else {
      cards.push({
        role: asked[1] || "Перемена",
        card: first,
        vacant: true,
        note: "Все черты молодые: знак стоит и сам не переходит.",
      })
    }
  }
  const spread = {
    id: "hexagram",
    title: question ? "Знак на вопрос" : "Книга перемен",
    cards,
    question,
    topic: detectTopic(question),
    throws,
    moving,
    change: cards[1]?.note || cards[0].note || "",
  }
  spread.reading = explainHex(spread)
  return spread
}

export function explainHex(spread) {
  const now = spread.cards[0]
  const later = spread.cards[1]
  const hex = now.card
  const asked = String(spread.question || "").trim()
  const here = applySign(hex, asked)
  const next = later && !later.vacant ? applySign(later.card, asked) : null
  const items = []
  if (later && !later.vacant) {
    items.push({
      role: later.role,
      name: `${later.card.mark} ${later.card.name}`,
      hint: later.card.hint,
      body: next.act,
      personal: "",
    })
  }
  const q = asked ? ` на вопрос «${asked}»` : " сегодня"
  let lead
  if (later && !later.vacant) {
    lead = `Сейчас: ${here.act} Так знак «${hex.name}» отвечает${q}. К перемене идёт знак «${later.card.name}».`
  } else if (later?.vacant) {
    lead = `${here.act} Так знак «${hex.name}» отвечает${q}. Черты молодые — второго знака нет, перемены не будет.`
  } else {
    lead = `${here.act} Так знак «${hex.name}» отвечает${q}.`
  }
  const marks = later && !later.vacant
    ? "Красные знаки на первой дощечке отмечают черты, из которых сложился второй знак."
    : ""
  const source = later?.vacant ? [now] : spread.cards.filter((item) => !item.vacant)
  const noteCards = source.map((item) => boundLot(item, asked))
  return {
    title: "Знак ответил",
    lead,
    items,
    note: synthesize({ cards: noteCards, question: asked || true, lot: "sign", end: marks, echo: true }),
  }
}

export function hexSvg(card, changing = -1) {
  const bars = [...(card.lines || [])].reverse()
  const gap = 11
  const y0 = 14
  const parts = bars.map((yang, i) => {
    const y = y0 + i * gap
    const glow = 5 - i === changing ? ` class="is-change"` : ""
    if (yang) return `<rect${glow} x="14" y="${y}" width="52" height="7" rx="1.2"/>`
    return `<rect${glow} x="14" y="${y}" width="20" height="7" rx="1.2"/><rect${glow} x="46" y="${y}" width="20" height="7" rx="1.2"/>`
  }).join("")
  const n = card?.n ? `<text class="hex-n" x="40" y="90" text-anchor="middle">${card.n}</text>` : ""
  return `<svg class="hex-face" viewBox="0 0 80 96" aria-hidden="true"><rect class="hex-bg" x="3" y="3" width="74" height="90" rx="5"/><rect class="hex-in" x="7" y="7" width="66" height="82" rx="3"/>${parts}${n}</svg>`
}
