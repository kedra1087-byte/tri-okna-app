/** Тон на вопрос «уходить или остаться»: светлая карта держит, а не выпроваживает. */
function leaveTone(card) {
  const stance = cardStance(card)
  if (stance === "stay") return "stay"
  if (stance === "go") return "go"
  if (stance === "wait" || stance === "hold") return "wait"
  const tone = verdictOf(card.id)
  if (tone === "no") return "go"
  if (tone === "yes") return "stay"
  return "wait"
}

function toneKey(card, face) {
  if (face === "leave") return leaveTone(card)
  return verdictOf(card.id)
}

/** Детерминированный выбор варианта привязки по карте: та же карта на тот же вопрос
 * всегда отвечает одинаково, а разные карты с одним тоном — с большой вероятностью разно. */
function tieFor(row, id) {
  const list = Array.isArray(row) ? row : [row].filter(Boolean)
  if (!list.length) return ""
  let hash = 0
  for (const ch of String(id)) hash = (hash * 33 + ch.charCodeAt(0)) >>> 0
  return list[hash % list.length]
}

export function faceLine(card, face, role = "", turn = 0) {
  if (!card || !face) return ""
  const ground = GROUND[card.id]
  const row = TIE[face]
  const tone = toneKey(card, face)
  const tie = tieFor(row?.[tone] || row?.wait, card.id)
  if (!ground || !tie) return ""
  return `${ground}\n\nПроще говоря: ${tie}`.trim()
}

function byScore(score, yes, no, wait) {
  if (score >= 1) return yes
  if (score <= -1) return no
  return wait
}

