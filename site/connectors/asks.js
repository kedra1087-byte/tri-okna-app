/** Тон на вопрос «уходить или остаться»: светлая карта держит, а не выпроваживает. */
function leaveTone(card) {
  const stance = cardStance(card)
  if (stance === "stay") return "stay"
  if (stance === "go") return "go"
  if (stance === "wait" || stance === "hold") return "wait"
  const tone = verdictOf(card.id)
  if (tone === "no") return "go"
  if (tone === "yes") return "stay"
  return "wait"
}

function toneKey(card, face) {
  if (face === "leave") return leaveTone(card)
  return verdictOf(card.id)
}

function lead(face, tone, role) {
  if (LOVE_FACES.has(face)) {
    const row = LOVE_LEAD[face]?.[tone] || LOVE_LEAD[face]?.wait
    if (!row) return ""
    return row[ROLE_SHIFT[role] || 0]
  }
  const row = LEAD[face]
  if (!row) return ""
  return row[tone] || row.wait || ""
}

function depthText(card, face, role, turn) {
  const layers = DEPTHS[card.id]
  if (!layers?.length) return ""
  const shift = LOVE_FACES.has(face) ? (ROLE_SHIFT[role] || 0) : 0
  return slot(card, layers, (turn >>> 0) + shift)
}

export function faceLine(card, face, role = "", turn = 0) {
  if (!card || !face) return ""
  const head = lead(face, toneKey(card, face), role)
  if (!head) return ""
  const depth = depthText(card, face, role, turn)
  return `${head} «${picture(card)}». ${depth}`.trim()
}

function byScore(score, yes, no, wait) {
  if (score >= 1) return yes
  if (score <= -1) return no
  return wait
}

