const LOVE_FACES = new Set(["feel", "loved", "future", "leave", "meet"])

export function preparedFace(question) {
  const key = String(question || "").toLowerCase().replace(/ё/g, "е").replace(/[^a-zа-я0-9]+/g, " ").trim()
  return PREPARED[key] || ""
}

function slot(card, list, turn = 0) {
  let hash = 0
  for (const ch of card.id) hash = (hash * 33 + ch.charCodeAt(0)) >>> 0
  const index = (hash + (turn >>> 0)) % list.length
  return list[index]
}

